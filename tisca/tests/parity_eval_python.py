#!/usr/bin/env python3
"""
TISCA v2 -- Python evaluator for the R<->Python parity suite (P2-T2).

Reads parity_reference.csv (generated by parity_generate_reference.R), evaluates
the equivalent function in the Python reference package (P2-T1), and writes a CSV
of computed values that parity_run.R diffs against the R reference.

Analytic rows -> compared at 1e-8; integer rows -> compared exactly.

The parity reference uses a deterministic seed-derived data construction for
paired_t and adjust_p_values so both languages reconstruct IDENTICAL inputs; only
the closed-form result differs.
"""

import argparse
import csv
import sys
import os

import numpy as np  # noqa: F401


def _load_py():
    sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)),
                                    "..", "python"))
    import tisca
    import tisca.planning as planning
    import tisca.multiplicity as multiplicity
    import tisca.inference as inference
    return planning, multiplicity, inference


def _as_num(v):
    if v is None or v == "NA" or v == "":
        return None
    return float(v)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--ref", required=True)
    ap.add_argument("--out", required=True)
    ap.add_argument("--limit", type=int, default=None)
    args = ap.parse_args()

    try:
        plan, mult, inf = _load_py()
    except (ImportError, ModuleNotFoundError) as e:
        with open(args.out, "w", newline="") as f:
            w = csv.writer(f)
            w.writerow(["case", "computed", "status"])
            w.writerow(["_PENDING_", "Python reference (P2-T1) not implemented", "pending"])
        print(f"PENDING: {e}")
        return 0

    ref = []
    with open(args.ref, newline="") as f:
        rd = csv.DictReader(f)
        for row in rd:
            ref.append(row)
            if args.limit and len(ref) >= args.limit:
                break

    with open(args.out, "w", newline="") as f:
        w = csv.writer(f)
        w.writerow(["case", "computed", "status"])
        for row in ref:
            case = row["case"]; fun = row["fun"]
            try:
                computed = evaluate(fun, row, plan, mult, inf)
                status = "ok"
            except Exception as e:  # noqa: BLE001
                computed = ""
                status = "error: " + str(e)
            w.writerow([case, computed, status])

    print("Computed parity values written to", args.out)
    return 0


def evaluate(fun, row, plan, mult, inf):
    mode = row["mode"]
    J = int(float(row["J"]))
    delta = _as_num(row["delta"])
    sigma = _as_num(row["sigma"])
    alpha = _as_num(row["alpha"])
    margin = _as_num(row["Delta"])

    if fun == "power":
        return str(plan.power_function(mode, J, delta, sigma, margin=margin, alpha=alpha))

    if fun == "sigma_ub":
        # gamma is carried in the delta column for the parity table
        gamma = delta if delta is not None else 0.20
        return str(plan.inflate_std(1.0, J, gamma=gamma))

    if fun == "solve_power_J":
        target_power = _as_num(row["target"]) or 0.80
        return str(plan.required_J_power(mode, delta, sigma, target_power, alpha,
                                         margin=margin))

    if fun == "solve_mcse_J":
        target_mcse = delta   # carried in the delta column
        return str(plan.required_J_mcse(sigma, target_mcse))

    if fun == "solve_halfwidth_J":
        halfwidth = delta     # carried in the delta column
        return str(plan.required_J_halfwidth(sigma, halfwidth, alpha or 0.05))

    if fun == "paired_t":
        # reconstruct D from the exact vector the R generator wrote
        D = np.array([float(x) for x in row["D_vec"].split(",")])
        alt = {"two.sided": "two-sided", "less": "less", "greater": "greater"}[mode]
        return str(inf.paired_t(D, alternative=alt)["p_value"])

    if fun == "adjust_p_values":
        pv = np.array([float(x) for x in row["pv_vec"].split(",")])
        meth = {"BH": "bh"}.get(mode, mode)
        adj = mult.p_adjust(pv, meth)
        return ",".join(f"{x:.12f}" for x in np.asarray(adj, dtype=float))

    if fun == "adj_alpha":
        name = {"romanowolf": "romano_wolf"}.get(mode, {"BH": "bh"}.get(mode, mode))
        alpha_plan, _note = mult.planning_alpha(name.lower(), int(J), alpha or 0.05, r=1)
        return str(alpha_plan)

    raise ValueError(f"unknown fun: {fun}")


if __name__ == "__main__":
    sys.exit(main())
